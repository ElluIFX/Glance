namespace glance::app
{
    const SyntaxThemePalette& syntax_theme_palette(
        SyntaxThemePreference theme,
        bool dark) noexcept
    {
        const auto index = std::min<std::size_t>(
            static_cast<std::uint32_t>(theme),
            themes.size() - 1);
        return dark ? themes[index].dark : themes[index].light;
    }
}
